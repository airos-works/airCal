#!/usr/bin/env bash
# Runs a real CalDAV server (Radicale 3.x) for airCal tests.
#
#   tools/caldav-server.sh [--daemon] [--seed] [--port N]   start (foreground unless --daemon)
#   tools/caldav-server.sh --seed      (server already up)  re-create the seed calendars and exit
#   tools/caldav-server.sh --check                          run the discovery/REPORT checks with curl
#   tools/caldav-server.sh --stop                           stop a --daemon server
#
# Radicale lives in a venv under $AIRCAL_RADICALE (default /mnt/HaikuWork/build/aircal-radicale),
# created on first use; collections are stored in $AIRCAL_RADICALE/data. Auth is htpasswd
# (plain) with user "tester", password "secret". The server listens on 0.0.0.0:5232, so the
# air/OS VM reaches it as http://10.0.2.2:5232/ and the LAN as http://192.168.1.200:5232/.
#
# --seed (re)creates, over plain HTTP, /tester/personal/ ("Personal", VEVENT+VTODO, #34C759)
# and /tester/shared/ ("Shared", VEVENT, #007AFF) with events relative to the current week.
set -euo pipefail
ROOT=${AIRCAL_RADICALE:-/mnt/HaikuWork/build/aircal-radicale}
PORT=${CALDAV_PORT:-5232}
USER_NAME=tester PASSWORD=secret
DAEMON=0 SEED=0 CHECK=0 STOP=0
while (($#)); do
	case $1 in
	--daemon) DAEMON=1 ;;
	--seed) SEED=1 ;;
	--check) CHECK=1 ;;
	--stop) STOP=1 ;;
	--port) PORT=$2; shift ;;
	-h | --help) sed -n '2,16p' "$0"; exit 0 ;;
	*) echo "unknown option $1" >&2; exit 2 ;;
	esac
	shift
done
PIDFILE=$ROOT/radicale.pid LOG=$ROOT/radicale.log
URL=http://127.0.0.1:$PORT

if ((STOP)); then
	if [[ -f $PIDFILE ]] && kill "$(cat "$PIDFILE")" 2>/dev/null; then echo "stopped radicale ($(cat "$PIDFILE"))"; fi
	rm -f "$PIDFILE"
	exit 0
fi

up() { curl -s -o /dev/null -m 2 "$URL/.well-known/caldav"; }

setup() {
	mkdir -p "$ROOT/data"
	if [[ ! -x $ROOT/venv/bin/radicale ]]; then
		echo "creating Radicale venv in $ROOT/venv" >&2
		python3 -m venv "$ROOT/venv"
		"$ROOT/venv/bin/pip" install -q radicale
	fi
	printf '%s:%s\n' "$USER_NAME" "$PASSWORD" >"$ROOT/users"
	cat >"$ROOT/config" <<-EOF
		# generated by apps/aircal/tools/caldav-server.sh
		[server]
		hosts = 0.0.0.0:$PORT

		[auth]
		type = htpasswd
		htpasswd_filename = $ROOT/users
		htpasswd_encryption = plain
		delay = 0

		[rights]
		type = owner_only

		[storage]
		filesystem_folder = $ROOT/data/collections

		[web]
		type = internal

		[logging]
		level = info
		mask_passwords = True
	EOF
}

seed() {
	"$ROOT/venv/bin/python" - "$URL" "$USER_NAME" "$PASSWORD" <<'PYEOF'
import base64, sys, urllib.error, urllib.request
from datetime import date, datetime, timedelta, timezone
url, user, pw = sys.argv[1:4]
auth = 'Basic ' + base64.b64encode(f'{user}:{pw}'.encode()).decode()

def call(method, path, body=None, ctype='application/xml; charset=utf-8', headers=None, ok=(200, 201, 204, 207)):
    req = urllib.request.Request(url + path, data=body.encode() if body else None, method=method,
                                 headers={'Authorization': auth, 'Content-Type': ctype, **(headers or {})})
    try:
        with urllib.request.urlopen(req) as r:
            status = r.status
    except urllib.error.HTTPError as e:
        status = e.code
    if status not in ok:
        sys.exit(f'{method} {path} -> HTTP {status}')
    return status

today = date.today()
mon = today - timedelta(days=today.weekday())
d = lambda n: (mon + timedelta(days=n)).strftime('%Y%m%d')
stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
utc = lambda n, hm: datetime.strptime(d(n) + hm, '%Y%m%d%H%M').strftime('%Y%m%dT%H%M00Z')

NY = """BEGIN:VTIMEZONE
TZID:America/New_York
BEGIN:DAYLIGHT
TZOFFSETFROM:-0500
TZOFFSETTO:-0400
TZNAME:EDT
DTSTART:19700308T020000
RRULE:FREQ=YEARLY;BYMONTH=3;BYDAY=2SU
END:DAYLIGHT
BEGIN:STANDARD
TZOFFSETFROM:-0400
TZOFFSETTO:-0500
TZNAME:EST
DTSTART:19701101T020000
RRULE:FREQ=YEARLY;BYMONTH=11;BYDAY=1SU
END:STANDARD
END:VTIMEZONE
"""

def ics(*components, tz=''):
    body = 'BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:-//airCal//caldav-server.sh seed//EN\r\nCALSCALE:GREGORIAN\r\n'
    body += tz.replace('\n', '\r\n')
    for c in components:
        body += c.strip().replace('\n', '\r\n') + '\r\n'
    return body + 'END:VCALENDAR\r\n'

def mkcalendar(path, name, color, comps, desc):
    call('DELETE', path, ok=(200, 204, 404))
    comp_xml = ''.join(f'<C:comp name="{c}"/>' for c in comps)
    call('MKCALENDAR', path, f'''<?xml version="1.0" encoding="utf-8"?>
<C:mkcalendar xmlns:D="DAV:" xmlns:C="urn:ietf:params:xml:ns:caldav" xmlns:I="http://apple.com/ns/ical/">
  <D:set><D:prop>
    <D:displayname>{name}</D:displayname>
    <C:calendar-description>{desc}</C:calendar-description>
    <I:calendar-color>{color}</I:calendar-color>
    <C:supported-calendar-component-set>{comp_xml}</C:supported-calendar-component-set>
  </D:prop></D:set>
</C:mkcalendar>''', ok=(201,))

def put(path, body):
    call('PUT', path, body, 'text/calendar; charset=utf-8', {'If-None-Match': '*'}, ok=(201,))

call('PROPFIND', f'/{user}/', '<propfind xmlns="DAV:"><prop><resourcetype/></prop></propfind>', headers={'Depth': '0'})
mkcalendar(f'/{user}/personal/', 'Personal', '#34C759', ['VEVENT', 'VTODO'], 'Personal events and to-dos')
mkcalendar(f'/{user}/shared/', 'Shared', '#007AFF', ['VEVENT'], 'Shared family/team calendar')

put(f'/{user}/personal/haircut.ics', ics(f"""BEGIN:VEVENT
UID:seed-haircut@aircal.test
DTSTAMP:{stamp}
DTSTART:{utc(2, '0030')}
DTEND:{utc(2, '0115')}
SUMMARY:Haircut
LOCATION:Main St Barber
DESCRIPTION:Timed event in UTC.
BEGIN:VALARM
ACTION:DISPLAY
DESCRIPTION:Haircut
TRIGGER:-PT15M
END:VALARM
END:VEVENT"""))
put(f'/{user}/personal/market.ics', ics(f"""BEGIN:VEVENT
UID:seed-market@aircal.test
DTSTAMP:{stamp}
DTSTART;VALUE=DATE:{d(5)}
DTEND;VALUE=DATE:{d(6)}
SUMMARY:Farmers market
TRANSP:TRANSPARENT
END:VEVENT"""))
put(f'/{user}/personal/rego.ics', ics(f"""BEGIN:VTODO
UID:seed-rego@aircal.test
DTSTAMP:{stamp}
CREATED:{stamp}
SUMMARY:Renew car registration
DUE;VALUE=DATE:{d(4)}
PRIORITY:1
STATUS:NEEDS-ACTION
END:VTODO"""))
put(f'/{user}/personal/library.ics', ics(f"""BEGIN:VTODO
UID:seed-library@aircal.test
DTSTAMP:{stamp}
CREATED:{stamp}
SUMMARY:Return library books
DUE;VALUE=DATE:{d(0)}
STATUS:COMPLETED
COMPLETED:{utc(0, '0300')}
PERCENT-COMPLETE:100
END:VTODO"""))
# Weekly on Thursdays in New York time, started three weeks ago (crosses the US DST change):
# last week's instance is excluded (EXDATE), this week's is moved to 20:00 (RECURRENCE-ID).
put(f'/{user}/shared/bookclub.ics', ics(f"""BEGIN:VEVENT
UID:seed-bookclub@aircal.test
DTSTAMP:{stamp}
DTSTART;TZID=America/New_York:{d(-18)}T190000
DTEND;TZID=America/New_York:{d(-18)}T200000
RRULE:FREQ=WEEKLY;BYDAY=TH;COUNT=12
EXDATE;TZID=America/New_York:{d(-4)}T190000
SUMMARY:Book club call
LOCATION:https://meet.example.com/bookclub
SEQUENCE:0
END:VEVENT""", f"""BEGIN:VEVENT
UID:seed-bookclub@aircal.test
DTSTAMP:{stamp}
RECURRENCE-ID;TZID=America/New_York:{d(3)}T190000
DTSTART;TZID=America/New_York:{d(3)}T200000
DTEND;TZID=America/New_York:{d(3)}T210000
SUMMARY:Book club call (moved to 8pm)
LOCATION:https://meet.example.com/bookclub
SEQUENCE:1
END:VEVENT""", tz=NY))
put(f'/{user}/shared/planning.ics', ics(f"""BEGIN:VEVENT
UID:seed-planning@aircal.test
DTSTAMP:{stamp}
DTSTART;TZID=America/New_York:{d(1)}T160000
DTEND;TZID=America/New_York:{d(1)}T173000
SUMMARY:Quarterly planning
DESCRIPTION:Timed event with a TZID.
END:VEVENT""", tz=NY))
put(f'/{user}/shared/offsite.ics', ics(f"""BEGIN:VEVENT
UID:seed-offsite@aircal.test
DTSTAMP:{stamp}
DTSTART;VALUE=DATE:{d(9)}
DTEND;VALUE=DATE:{d(11)}
SUMMARY:Team offsite
END:VEVENT"""))
print('seeded /%s/personal/ (2 events, 2 to-dos) and /%s/shared/ (3 events)' % (user, user))
PYEOF
}

check() {
	local fail=0 out
	c() { curl -s -u "$USER_NAME:$PASSWORD" "$@"; }
	t() { # t "description" grep-pattern...  (reads the response on stdin)
		local what=$1; shift; out=$(cat)
		for p in "$@"; do grep -q -- "$p" <<<"$out" || { echo "FAIL $what: no '$p'"; echo "$out" | head -c 1500; echo; fail=1; return; }; done
		echo "ok   $what"
	}
	curl -s -o /dev/null -w '%{http_code}' -X PROPFIND "$URL/" | t "unauthenticated PROPFIND is 401" 401
	curl -s -o /dev/null -w '%{http_code} %{redirect_url}' "$URL/.well-known/caldav" | t ".well-known/caldav redirects to /" "^30[12] $URL/$"
	c -X PROPFIND -H 'Depth: 0' "$URL/" --data '<propfind xmlns="DAV:"><prop><current-user-principal/></prop></propfind>' |
		t "PROPFIND / -> current-user-principal" "current-user-principal><href>/$USER_NAME/</href>"
	c -X PROPFIND -H 'Depth: 0' "$URL/$USER_NAME/" --data '<propfind xmlns="DAV:" xmlns:C="urn:ietf:params:xml:ns:caldav"><prop><C:calendar-home-set/><displayname/></prop></propfind>' |
		t "PROPFIND principal -> calendar-home-set" "calendar-home-set><href>/$USER_NAME/</href>"
	c -X PROPFIND -H 'Depth: 1' "$URL/$USER_NAME/" --data '<propfind xmlns="DAV:" xmlns:C="urn:ietf:params:xml:ns:caldav" xmlns:CS="http://calendarserver.org/ns/" xmlns:I="http://apple.com/ns/ical/"><prop><resourcetype/><displayname/><I:calendar-color/><C:supported-calendar-component-set/><CS:getctag/><sync-token/></prop></propfind>' |
		t "PROPFIND home Depth:1 lists both calendars" "<href>/$USER_NAME/personal/</href>" "<href>/$USER_NAME/shared/</href>" \
			"displayname>Personal<" "displayname>Shared<" "calendar-color>#34C759<" 'comp name="VTODO"' "getctag>" "sync-token>"
	local start end
	start=$(date -u -d '-21 days' +%Y%m%dT000000Z) end=$(date -u -d '+21 days' +%Y%m%dT000000Z)
	c -X REPORT -H 'Depth: 1' "$URL/$USER_NAME/shared/" --data "<C:calendar-query xmlns:D=\"DAV:\" xmlns:C=\"urn:ietf:params:xml:ns:caldav\"><D:prop><D:getetag/><C:calendar-data/></D:prop><C:filter><C:comp-filter name=\"VCALENDAR\"><C:comp-filter name=\"VEVENT\"><C:time-range start=\"$start\" end=\"$end\"/></C:comp-filter></C:comp-filter></C:filter></C:calendar-query>" |
		t "calendar-query REPORT (VEVENT, time-range) on Shared" "bookclub.ics" "planning.ics" "offsite.ics" "RECURRENCE-ID;TZID=America/New_York" "EXDATE;TZID=America/New_York" "getetag>"
	c -X REPORT -H 'Depth: 1' "$URL/$USER_NAME/personal/" --data '<C:calendar-query xmlns:D="DAV:" xmlns:C="urn:ietf:params:xml:ns:caldav"><D:prop><D:getetag/><C:calendar-data/></D:prop><C:filter><C:comp-filter name="VCALENDAR"><C:comp-filter name="VTODO"/></C:comp-filter></C:filter></C:calendar-query>' |
		t "calendar-query REPORT (VTODO) on Personal" "rego.ics" "library.ics" "STATUS:COMPLETED"
	c -X REPORT -H 'Depth: 1' "$URL/$USER_NAME/personal/" --data '<sync-collection xmlns="DAV:"><sync-token/><sync-level>1</sync-level><prop><getetag/></prop></sync-collection>' |
		t "sync-collection REPORT (initial) on Personal" "haircut.ics" "market.ics" "<sync-token>"
	return $fail
}

if ((CHECK)); then check; exit; fi
if up; then
	if ((SEED)); then setup >/dev/null 2>&1 || true; seed; exit; fi
	echo "a server already answers on port $PORT" >&2; exit 1
fi
setup
RAD=("$ROOT/venv/bin/radicale" --config "$ROOT/config")
wait_up() { for _ in $(seq 100); do up && return 0; sleep 0.1; done; echo "radicale did not start; see $LOG" >&2; return 1; }
if ((DAEMON)); then
	nohup "${RAD[@]}" >"$LOG" 2>&1 &
	echo $! >"$PIDFILE"
	wait_up
	echo "radicale running on 0.0.0.0:$PORT (pid $(cat "$PIDFILE"), log $LOG)"
	if ((SEED)); then seed; fi
	exit 0
fi
if ((SEED)); then
	"${RAD[@]}" &
	PID=$!
	trap 'kill $PID 2>/dev/null' INT TERM
	wait_up && seed
	wait $PID
else
	exec "${RAD[@]}"
fi
